"""Frozen-baseline evaluation under the player-disjoint protocol.

Two things separate this from `scoutlens.evaluation.run_report`, and both
are deliberate:

1. **The scaler is fit on train only.** The published experiments fit it on
   the population being compared (D008), which is right for a descriptive
   result and wrong for a confirmatory one. Here `fit_scaler` sees training
   rows and nothing else.
2. **Candidate pools are within-split.** A query from a split is ranked
   only against period-B profiles of players in that same split, so a test
   query can never retrieve a training player.

Consequence, stated in the protocol and repeated here because it is the
easiest thing to misread: split-level absolute MRR is *not* comparable to
the published full-population numbers. Pools are smaller, so retrieval is
easier. Only the within-split paired delta is the object of study.
"""

from __future__ import annotations

import dataclasses

import polars as pl

from scoutlens.benchmark.features import CANONICAL_28
from scoutlens.benchmark.protocol import PROTOCOL, assert_test_set_unlocked
from scoutlens.benchmark.split import SPLITS, TEST, TRAIN
from scoutlens.evaluation.retrieval import (
    bootstrap_mrr_delta,
    compute_metrics,
    run_baseline_a_retrieval,
    run_baseline_b_retrieval,
    select_eligible_both_periods,
)
from scoutlens.evaluation.similarity import Scaler, apply_scaler, fit_scaler

PERIOD_A = "A"
PERIOD_B = "B"


def build_evaluation_population(
    period_profiles: pl.DataFrame,
    role_lookup: pl.DataFrame,
    minutes_threshold: int,
    competition_ids: list[int],
) -> pl.DataFrame:
    """The rows the benchmark can actually query: eligible in both periods,
    with a role attached. Fails closed on a missing role rather than
    dropping the player — a silently dropped row changes the population
    without changing the manifest."""
    eligible = select_eligible_both_periods(period_profiles, minutes_threshold, competition_ids)
    joined = eligible.join(role_lookup, on="player_id", how="left")
    missing = joined.filter(pl.col("role").is_null())
    if missing.height:
        ids = sorted(set(missing["player_id"].to_list()))[:10]
        raise ValueError(f"{missing.height} eligible rows have no role (first player_ids: {ids})")
    return joined


SIGNIFICANT_DIGITS = 12
"""See `PROTOCOL["preprocessing"]["fitted_statistic_precision"]`."""


def _quantize(value: float) -> float:
    return float(f"{value:.{SIGNIFICANT_DIGITS}g}")


def quantize_scaler(scaler: Scaler) -> Scaler:
    """Round fitted statistics to a fixed precision.

    Polars reduces sums in parallel, so `mean`/`std` over identical input can
    differ by 1-2 ULPs between runs. That never moves an integer rank — the
    metrics are bit-identical without this — but it does make the serialized
    scaler irreproducible, and a published artifact that cannot be
    regenerated byte-for-byte is not publishable under the modeling contract.
    Quantizing costs ~1e-12 relative on each z-score.
    """
    return {
        column: None if fit is None else (_quantize(fit[0]), _quantize(fit[1]))
        for column, fit in scaler.items()
    }


def fit_train_scaler(
    population_with_split: pl.DataFrame, feature_columns: list[str]
) -> Scaler:
    """Fit the scaler on training rows only. Isolated as its own function so
    a test can assert directly that no validation or test row reaches it."""
    train_rows = population_with_split.filter(pl.col("split") == TRAIN)
    if not train_rows.height:
        raise ValueError("no training rows to fit the scaler on")
    return quantize_scaler(fit_scaler(train_rows, feature_columns))


def _metrics_dict(ranks: pl.DataFrame) -> dict:
    return dataclasses.asdict(compute_metrics(ranks["rank"].to_list()))


def evaluate_split(
    population_with_split: pl.DataFrame,
    scaler: Scaler,
    split: str,
    *,
    feature_columns: tuple[str, ...] = CANONICAL_28,
    n_resamples: int | None = None,
    seed: int | None = None,
    allow_test: bool = False,
) -> dict:
    """Frozen Baseline A and Baseline B on one split, global and within-role.

    `allow_test` must be set explicitly to evaluate the test split, and even
    then the protocol lock still has to be open. Two independent gates, so
    neither a stray argument nor an unrecorded protocol alone is enough.
    """
    if split not in SPLITS:
        raise ValueError(f"unknown split {split!r}; expected one of {SPLITS}")
    if split == TEST:
        if not allow_test:
            raise PermissionError(
                "refusing to evaluate the test split without allow_test=True; "
                "the test split is opened once, deliberately (scoutlens-qop.1)"
            )
        assert_test_set_unlocked()

    interval = PROTOCOL["metrics"]["paired_interval"]
    n_resamples = interval["n_resamples"] if n_resamples is None else n_resamples
    seed = interval["seed"] if seed is None else seed

    columns = list(feature_columns)
    rows = population_with_split.filter(pl.col("split") == split)
    if not rows.height:
        raise ValueError(f"split {split!r} has no rows")

    standardized = apply_scaler(rows, columns, scaler)
    queries = standardized.filter(pl.col("period") == PERIOD_A)
    candidates = standardized.filter(pl.col("period") == PERIOD_B)
    if not queries.height or not candidates.height:
        raise ValueError(f"split {split!r} is missing one of the two periods")

    result: dict = {
        "split": split,
        "n_players": rows["player_id"].n_unique(),
        "n_queries": queries.height,
        "candidate_pool_size": candidates.height,
        "conditions": {},
    }

    for condition, scope in (("global", None), ("within_role", "role")):
        ranks_a = run_baseline_a_retrieval(queries, candidates, scope_column=scope)
        ranks_b = run_baseline_b_retrieval(queries, candidates, columns, scope_column=scope)
        result["conditions"][condition] = {
            "baseline_a": _metrics_dict(ranks_a),
            "baseline_b": _metrics_dict(ranks_b),
            "mrr_delta": bootstrap_mrr_delta(ranks_a, ranks_b, n_resamples=n_resamples, seed=seed),
        }

    result["by_role"] = _by_role(queries, candidates, columns)
    return result


def _by_role(queries: pl.DataFrame, candidates: pl.DataFrame, columns: list[str]) -> dict:
    """Within-role Baseline B per role, with the reportable-minimum flag the
    subgroup decision rule depends on. Reported for every role; only roles at
    or above the minimum can gate a KEEP."""
    minimum = PROTOCOL["subgroups"]["reportable_minimum_queries"]
    by_role: dict = {}
    for role in sorted(queries["role"].unique().to_list()):
        role_queries = queries.filter(pl.col("role") == role)
        ranks_b = run_baseline_b_retrieval(role_queries, candidates, columns, scope_column="role")
        if not ranks_b.height:
            continue
        by_role[role] = {
            "n_queries": role_queries.height,
            "baseline_b": _metrics_dict(ranks_b),
            "gates_decision": role_queries.height >= minimum,
        }
    return by_role
